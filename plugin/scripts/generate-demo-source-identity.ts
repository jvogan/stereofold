/** Regenerate browser display provenance from the index and checked lessons.
 * Run: pnpm --dir plugin exec tsx scripts/generate-demo-source-identity.ts
 */
import assert from 'node:assert/strict';
import { writeFile } from 'node:fs/promises';
import { compositeRecipePath, readCompositeRecipe } from '../src/demo-composite-files.js';
import { compositeSourceProvenance } from '../src/demo-rigid-composite.js';
import { readBundledDemoCoordinates } from '../src/bundled-demo-coordinates.js';
import { readDemoIndex, readDemoLesson } from './quest-demo.js';

// Keep the established short readout names for the original derived subsets.
const shortTitles: Record<string, string> = {
  '5SYF-lattice-op2-7.cif': 'Microtubule wall',
  '5SYF-protofilament-op1-14.cif': 'Tubulin protofilament',
  '5SYF-monomer-alpha.cif': 'Alpha tubulin',
};
const index = await readDemoIndex();
const records: Record<string, Record<string, unknown>> = {};
for (const demo of index.demos) {
  for (const entry of [demo, ...(demo.stages ?? []).map(stage => ({ ...demo, ...stage }))]) {
    const { coordinates } = entry;
    const derivation = coordinates.derivation;
    if (!derivation) continue;
    // Uses the same schema and coordinate-digest check as the demo launcher.
    await readDemoLesson(entry);
    let scope: string;
    let assembly: { assemblyId?: string } = {};
    let provenance: Record<string, unknown> = {};
    switch (derivation.kind) {
      case 'bundled-file': {
        await readBundledDemoCoordinates(derivation.path, coordinates.sha256);
        assert.ok(entry.sourceId, `${entry.lesson}: bundled coordinates need a source identifier`);
        provenance = { sourceId: entry.sourceId, sources: entry.sources };
        scope = 'bundled coordinates';
        break;
      }
      case 'assembly-operator-subset': {
        const assemblyId = coordinates.download?.match(/-assembly([^/.]+)\.cif$/)?.[1];
        assert.ok(assemblyId, `${entry.lesson}: assembly download must name its assembly`);
        assembly = { assemblyId };
        scope = `assembly ${assemblyId} subset`;
        break;
      }
      case 'deposited-chain-subset': scope = 'deposited chain subset'; break;
      case 'prepared-rigid-composite': {
        // The deposited entries a wearer reads, in the recipe's own order, each once.
        const recipe = await readCompositeRecipe(compositeRecipePath(derivation.recipe));
        const sources = compositeSourceProvenance(recipe);
        provenance = { entries: sources.filter(source => source.kind === 'deposited').map(source => source.id), sources };
        scope = 'prepared rigid composite';
        break;
      }
      default: throw Error(`Unsupported demo derivation: ${JSON.stringify(derivation)}`);
    }
    const record = { ...(entry.pdbId ? { pdbId: entry.pdbId } : {}), title: shortTitles[coordinates.file] ?? entry.title,
      scope, ...derivation, ...assembly, ...provenance };
    const previous = records[coordinates.sha256];
    if (previous) {
      // A staged entry can have a shorter title, but never different provenance.
      assert.deepEqual({ ...record, title: previous.title }, previous);
    } else records[coordinates.sha256] = record;
  }
}

const output = `/** Generated by plugin/scripts/generate-demo-source-identity.ts.
 * Display provenance only; scientific source and assembly IDs stay unchanged. */
const freeze = value => {
  if (value && typeof value === 'object') {
    Object.values(value).forEach(freeze);
    Object.freeze(value);
  }
  return value;
};
export const DEMO_DERIVED_SOURCES = freeze(${JSON.stringify(records, null, 2)});

export function demoSourceIdentity(sha256) {
  return typeof sha256 === 'string' && Object.hasOwn(DEMO_DERIVED_SOURCES, sha256)
    ? DEMO_DERIVED_SOURCES[sha256] : undefined;
}
`;
await writeFile(new URL('../../lab/browser-roundtrip/demo-source-identity.mjs', import.meta.url), output);
console.log(`Generated ${Object.keys(records).length} derived demo identities.`);

/** Offline catalog sizing: node --import tsx scripts/measure-experience-catalog.ts
 * src/experience-catalog-sizes.ts 4FFB=/path/to/4FFB.cif ...
 * Coordinates stay local. Missing sources are recorded explicitly, never guessed.
 */
import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { PLUGIN_VERSION } from 'molstar/lib/commonjs/mol-plugin/version.js';
import { experienceGeometry } from '../src/experience-budget.js';
import { inspectionSourcePdbId } from '../src/inspection-catalog.js';
import { MOLECULAR_EXPERIENCES } from '../src/molecular-experience.js';

const [output,...inputs]=process.argv.slice(2);
if(!output)throw Error('Provide an output TypeScript path and PDB=/path/to/source.cif inputs.');
const paths=new Map(inputs.map(input=>{
  const separator=input.indexOf('=');
  if(separator<1)throw Error('Source inputs must use PDB=/path/to/source.cif.');
  return [input.slice(0,separator).toUpperCase(),input.slice(separator+1)];
}));
const entries:Record<string,unknown>={};
for(const stage of MOLECULAR_EXPERIENCES.flatMap(experience=>experience.stages)) {
  const {pdbId}=stage.source,modelNumber=stage.source.modelNumber??1;
  const key=`${pdbId}:${stage.assembly.assemblyId}:${modelNumber}`;
  if(entries[key])continue;
  const path=paths.get(pdbId);
  if(!path) {
    entries[key]={reason:`${pdbId} model ${modelNumber}, assembly ${stage.assembly.assemblyId} has no cached atom, bond, or residue counts. Its coordinates must load on the host before this chapter can be sized.`};
    continue;
  }
  const text=await readFile(path,'utf8');
  if((await inspectionSourcePdbId(text))?.toUpperCase()!==pdbId)throw Error(`Source bytes do not identify ${pdbId}.`);
  entries[key]={sourceSha256:createHash('sha256').update(text,'utf8').digest('hex'),
    counts:await experienceGeometry(text,stage,modelNumber)};
}
await writeFile(output,`// Generated by scripts/measure-experience-catalog.ts from public coordinate files.
// Counts describe the whole declared model/assembly, including hidden atoms.
import type { ExperienceGeometry } from './experience-budget.js';

export const EXPERIENCE_CATALOG_SIZES: {
  molstarVersion: string; derivation: string;
  entries: Record<string, { sourceSha256?: string; counts?: ExperienceGeometry; reason?: string }>;
} = ${JSON.stringify({molstarVersion:PLUGIN_VERSION,
  derivation:'experienceGeometry: declared model and full Mol* assembly, including hidden atoms and real bonds; no visibility discount.',entries},null,2)};
`);
